"""Generates the pixel font and the screen of Prism's billboard (billboard.lua): DejaVu Sans Mono Bold drawn without anti-aliasing at 11 px, each pixel then made 3 x 3, so the letters look like the dots of an LED screen.

Needs Pillow and DejaVu Sans Mono Bold (Vera / DejaVu licence, see LICENSE.fonts). Writes, into mods/crystalminer:
  textures/crystalminer_px_<ink>_<code point>.png   one glyph per character and ink
  textures/crystalminer_billboard_screen.png         the empty screen with its frame
  pixel_font.lua                                     the cell size and the characters that exist
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.join(os.path.dirname(__file__), "..", "mods", "crystalminer")
OUT = os.path.join(ROOT, "textures")
FONT_PATHS = ["/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf", "C:/Windows/Fonts/DejaVuSansMono-Bold.ttf",
              "/Library/Fonts/DejaVuSansMono-Bold.ttf"]
SIZE, SCALE = 11, 3

# Inks: answer text, the question, Prism's name, highlighted words, notes.
INKS = {"w": (236, 240, 255), "c": (120, 220, 255), "v": (208, 128, 255), "y": (255, 206, 92), "g": (128, 136, 160)}
EXTRA = "°·—–‘’“”…•×÷±≈→←²³₁₂₃₄₆éèêëáàâäöüçñÅ"

# The billboard's screen: 12 x 7 nodes at 128 px per node.
W, H = 1536, 896
HEADER = 84


def font():
    for p in FONT_PATHS:
        if os.path.exists(p):
            return ImageFont.truetype(p, SIZE)
    sys.exit("DejaVu Sans Mono Bold not found; install fonts-dejavu")


def cell(f):
    asc, desc = f.getmetrics()
    return round(f.getlength("M")), asc + desc, asc


def glyph(f, ch, cw, ch_h, asc, ink):
    """The character on its own cell, 1 bit, scaled up; None if the font has nothing to draw."""
    mask = Image.new("L", (cw, ch_h), 0)
    d = ImageDraw.Draw(mask)
    d.fontmode = "1"
    if ch == "-":
        # Drawn without anti-aliasing at this size, the font's hyphen is a single dot; this one is a bar, as wide as the stroke of an x.
        top = asc - round(f.getbbox("x")[3] - f.getbbox("x")[1]) // 2 - 1
        d.rectangle([1, top, cw - 2, top + 1], fill=255)
    else:
        d.text((0, asc), ch, font=f, fill=255, anchor="ls")
    if mask.getbbox() is None:
        return None
    img = Image.new("RGBA", (cw, ch_h), (0, 0, 0, 0))
    img.paste((*ink, 255), (0, 0), mask)
    return img.resize((cw * SCALE, ch_h * SCALE), Image.NEAREST)


def screen():
    """A dark screen with faint scan lines in a violet frame, and a header strip."""
    img = Image.new("RGBA", (W, H), (11, 16, 32, 255))
    d = ImageDraw.Draw(img)
    for y in range(0, H, SCALE * 2):
        d.line([(0, y), (W, y)], fill=(15, 21, 40, 255))
    d.rectangle([0, 0, W - 1, HEADER], fill=(43, 35, 70, 255))
    d.line([(0, HEADER), (W, HEADER)], fill=(122, 82, 208, 255), width=3)
    frame, edge = 18, (122, 82, 208, 255)
    d.rectangle([0, 0, W - 1, H - 1], outline=(66, 36, 128, 255), width=frame)
    d.rectangle([frame - 4, frame - 4, W - frame + 3, H - frame + 3], outline=edge, width=4)
    for x, y in ((frame + 10, H - frame - 22), (W - frame - 22, H - frame - 22)):   # status lights
        d.rectangle([x, y, x + 11, y + 11], fill=(120, 230, 255, 255))
    return img


def main():
    f = font()
    cw, ch_h, asc = cell(f)
    codes = [c for c in range(32, 127)] + [ord(c) for c in EXTRA]
    have = []
    for code in codes:
        ch = chr(code)
        drew = False
        for ink, rgb in INKS.items():
            img = glyph(f, ch, cw, ch_h, asc, rgb)
            if img is not None:
                img.save(os.path.join(OUT, "crystalminer_px_%s_%d.png" % (ink, code)), optimize=True)
                drew = True
        if drew or code == 32:
            have.append(code)
    screen().save(os.path.join(OUT, "crystalminer_billboard_screen.png"), optimize=True)
    with open(os.path.join(ROOT, "pixel_font.lua"), "w", encoding="utf-8", newline="\n") as out:
        out.write("-- Generated by tools/make_pixel_font.py: the pixel font of Prism's billboard. Do not edit.\n")
        out.write("return {\n")
        out.write("\tw = %d, h = %d, scale = %d, screen = { w = %d, h = %d, header = %d },\n" % (cw * SCALE, ch_h * SCALE, SCALE, W, H, HEADER))
        out.write("\tinks = { %s },\n" % ", ".join('"%s"' % k for k in INKS))
        out.write("\thave = {\n")
        for i in range(0, len(have), 16):
            out.write("\t\t" + " ".join("[%d] = true," % c for c in have[i:i + 16]) + "\n")
        out.write("\t},\n}\n")
    print("%d characters, cell %d x %d px" % (len(have), cw * SCALE, ch_h * SCALE))


if __name__ == "__main__":
    main()
